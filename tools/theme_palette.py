"""Reach color palette, authored in OKLCH.

Writes src/core/theme_palette.h, the sRGB macros that the theme tables in theme.c use.
Edit the tables below, then run this script. `--check` only reports whether the header is stale.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "src" / "core" / "theme_palette.h"

# Chroma and hue shared by every neutral step. White and black stay untinted to remain inside sRGB.
NEUTRAL_TINT = (0.004, 285)

# (name, L): neutral steps by OKLCH lightness, tuned by eye.
NEUTRALS = [
    ("DARK_SURFACE_BASE", 0.181),
    ("DARK_SURFACE_RAISED", 0.238),
    ("DARK_SURFACE_ELEVATED", 0.262),
    ("DARK_DIVIDER", 0.267),
    ("DARK_BORDER", 0.519),
    ("LIGHT_SURFACE_BASE", 1.000),
    ("LIGHT_SURFACE_RAISED", 0.970),
    ("LIGHT_SURFACE_ELEVATED", 0.952),
    ("LIGHT_DIVIDER", 0.952),
    ("LIGHT_BORDER", 0.675),
    ("DARK_TEXT", 1.000),
    ("LIGHT_TEXT", 0.000),
    ("FILL", 0.570),
]

# (name, opacity): text strengths applied to the per-mode text base.
TEXT_STRENGTHS = [
    ("PRIMARY", 0.85),
    ("SECONDARY", 0.55),
    ("TERTIARY", 0.30),
    ("QUATERNARY", 0.18),
]

# (name, opacity): accent strengths applied to the resolved accent fill or accent text.
ACCENT_STRENGTHS = [
    ("FAINT", 0.12),
    ("TINT", 0.20),
    ("SELECTION", 0.30),
    ("MUTED", 0.55),
]

# (name, dark opacity, light opacity): fill strengths applied to FILL behind content.
FILL_STRENGTHS = [
    ("PRIMARY", 0.36, 0.20),
    ("SECONDARY", 0.32, 0.16),
    ("TERTIARY", 0.24, 0.12),
    ("QUATERNARY", 0.18, 0.08),
]

# (family, hue, deep (L, C), bright (L, C), ink (L, C)). Fills use deep in dark mode and bright in
# light mode; colored marks the reverse; small colored text in light mode uses ink.
HUE_FAMILIES = [
    ("BLUE", 258.0, (0.52, 0.185), (0.667, 0.178), (0.37, 0.12)),
    ("CYAN", 236.4, (0.571, 0.123), (0.7396, 0.1404), (0.37, 0.077)),
    ("TEAL", 210.2, (0.552, 0.089), (0.77, 0.109), (0.37, 0.058)),
    ("GREEN", 150.5, (0.572, 0.146), (0.7602, 0.1875), (0.37, 0.088)),
    ("PURPLE", 305.3, (0.492, 0.204), (0.651, 0.214), (0.37, 0.133)),
    ("LAVENDER", 296.6, (0.52, 0.175), (0.717, 0.149), (0.37, 0.148)),
    ("ORANGE", 53.8, (0.598, 0.147), (0.736, 0.156), (0.37, 0.09)),
    ("YELLOW", 83.0, (0.6097, 0.1221), (0.834, 0.155), (0.37, 0.076)),
    ("RED", 31.5, (0.56, 0.177), (0.705, 0.165), (0.37, 0.115)),
]

# (name, L, C, h): OKLCH lightness 0-1, chroma, hue in degrees.
PALETTE = [
    ("PURE_WHITE", 1.000, 0.000, 0),
    ("PURE_BLACK", 0.000, 0.000, 0),
]


def _encode(linear: float) -> float:
    if linear <= 0.0031308:
        return 12.92 * linear
    return 1.055 * linear ** (1 / 2.4) - 0.055


def oklch_to_rgb8(name: str, lightness: float, chroma: float, hue: float) -> tuple[int, ...]:
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
    )
    channels = tuple(round(_encode(value) * 255) for value in linear)
    if any(channel < 0 or channel > 255 for channel in channels):
        raise ValueError(f"{name} is outside sRGB: {channels}")
    return channels


def render() -> str:
    lines = [
        "// Generated by tools/theme_palette.py from its OKLCH palette. Edit the script, not this file.",
        "#ifndef REACH_THEME_PALETTE_H",
        "#define REACH_THEME_PALETTE_H",
        "",
        "#define REACH_RGB8(r, g, b, a) {(r) / 255.0f, (g) / 255.0f, (b) / 255.0f, (a)}",
        "",
    ]
    chroma, hue = NEUTRAL_TINT
    neutrals = [(name, lightness, chroma if 0 < lightness < 1 else 0, hue) for name, lightness in NEUTRALS]
    families = [
        (f"{family}_{level}", lightness, chroma, hue)
        for family, hue, *levels in HUE_FAMILIES
        for level, (lightness, chroma) in zip(("DEEP", "BRIGHT", "INK"), levels)
    ]
    for name, lightness, chroma, hue in neutrals + PALETTE + families:
        r, g, b = oklch_to_rgb8(name, lightness, chroma, hue)
        lines.append(f"#define REACH_{name}(a) REACH_RGB8({r}, {g}, {b}, a)")
    lines.append("")
    for name, opacity in TEXT_STRENGTHS:
        lines.append(f"#define REACH_TEXT_{name} {opacity:.2f}f")
    for name, opacity in ACCENT_STRENGTHS:
        lines.append(f"#define REACH_ACCENT_{name} {opacity:.2f}f")
    for name, dark, light in FILL_STRENGTHS:
        lines.append(f"#define REACH_DARK_FILL_{name} {dark:.2f}f")
        lines.append(f"#define REACH_LIGHT_FILL_{name} {light:.2f}f")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def check() -> list[str]:
    try:
        expected = render()
    except ValueError as error:
        return [f"tools/theme_palette.py: {error}"]
    actual = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
    if actual != expected:
        return ["src/core/theme_palette.h is stale; run tools/theme_palette.py"]
    return []


def main() -> int:
    if "--check" in sys.argv[1:]:
        problems = check()
        for problem in problems:
            print(problem)
        return 1 if problems else 0
    HEADER.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
